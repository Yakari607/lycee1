                        <p>Le titulaire de ce bac pro sait analyser l'ensemble des données techniques et utiliser la chaîne des données numériques (conception assistée par ordinateur, fabrication assistée par ordinateur...).</p>
                        <p>Lors du lancement et du suivi de la production, il prépare les outils et les outillages. Il conçoit un programme à partir d'une définition numérique et à l'aide de logiciels de fabrication assistée par ordinateur puis il effectue la simulation du programme. Il implante et transfère les données numériques.</p>
                        <p>Il règle et met en œuvre le système. Il choisit les matériels de mesure et de contrôle. Il installe et règle les outils et les outillages. Il réalise les pièces dans le respect de la qualité, des délais et des coûts. Il assure la maintenance de premier niveau de l'ensemble du système de production.</p>
                        <p>Le technicien travaille en équipe et collabore avec les différents services de l'entreprise. Il possède des connaissances en gestion de production appliquées au contexte de l'atelier.</p>
