                <div class="formation-block">
                    <h3><i class="fas fa-briefcase"></i> Le métier</h3>
                    <p>Le titulaire de ce CAP fabrique tous types d'enseigne. Il en assure la pose. Il effectue l'entretien courant et les réparations simples. Il fabrique des enseignes en verre, en plastique (PMMA-PVC) et matériaux composites, en métal. Il réalise aussi des enseignes en bandeau et caisson. Il maîtrise les techniques de découpage, d'usinage, de conformation à froid et à chaud, d'assemblage et de collage des matériaux.</p>
                    
                    <p>En verrerie, il réalise le soufflage et le pompage des tubes de verre. Pour la finition de l'ouvrage, il applique la peinture et si nécessaire intègre les équipements électriques.</p>
                    
                    <p>Le travail en atelier terminé, il se rend sur le site pour la pose, commence par la préparation du chantier, puis trace un plan de pose à l'emplacement défini. Ensuite, il scelle l'armature et assemble dans l'ordre requis les éléments de l'enseigne. Il achève l'installation par le raccordement électrique, en vérifie la conformité et procède aux essais de contrôle.</p>
                    
                    <p>Ses activités supposent qu'il sache organiser les postes de travail, définir et respecter l'ordre des opérations. L'autonomie dont il dispose implique une bonne connaissance et une application stricte des consignes de sécurité, notamment lors des opérations de pompages et lors des interventions sur l'installation.</p>
                    
                    <p>Il est capable de recueillir et d'analyser les informations nécessaires à son travail. Il communique avec l'équipe, les services de l'entreprise, le client. Il sait exécuter des croquis, tracer différents types de lettres ainsi qu'effectuer le tracé d'un tube à cathode froide.</p>
