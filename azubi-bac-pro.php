                            <li>20h / année sont consacrées à l'acquisition des nécessaires compétences interculturelles en vue d'une insertion réussie en entreprise.</li>
                        </ul>
                        
                        <p>Les périodes de formation en milieu professionnel dans le pays partenaire de 6 à 8 semaines permettent à l'apprenant de s'adapter à la différence et de vivre une mobilité.</p>
