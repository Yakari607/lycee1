                        <p>Elle repose sur un partenariat solide sur l'ensemble du cursus de formation (3 ans) avec un établissement de formation du pays voisin engagé dans le même dispositif. Ce partenariat s'appuie également sur les relations avec le monde économique.</p>
                        
